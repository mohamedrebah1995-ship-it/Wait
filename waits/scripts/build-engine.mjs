// Generates the extension's copy of the stacking engine from src/stackEngine.js, so there is still ONE
// source. JavaScriptCore has no ES modules: the module body is wrapped in an IIFE that exposes a global
// StackEngine. Run by `npm run build:engine` (and by cap:sync). Never edit the output by hand.
import { readFileSync, writeFileSync } from "node:fs";
import vm from "node:vm";

const SRC = new URL("../src/stackEngine.js", import.meta.url);
const OUT = new URL("../ios/App/DelivrScreenReader/StackEngine.js", import.meta.url);

const src = readFileSync(SRC, "utf8");
if (/^\s*import\s/m.test(src)) throw new Error("stackEngine.js must stay import-free to run in JavaScriptCore");
const names = [...src.matchAll(/^export (?:function|const) (\w+)/gm)].map(m => m[1]);
const body = src.replace(/^export (function|const) /gm, "$1 ");
const out = `// GENERATED by scripts/build-engine.mjs from src/stackEngine.js. Do not edit.\n` +
  `var StackEngine = (function () {\n${body}\nreturn { ${names.join(", ")} };\n})();\n`;

// Prove the output loads and behaves like the module before writing it.
const ctx = {}; vm.createContext(ctx); vm.runInContext(out, ctx);
const engine = vm.runInContext("StackEngine", ctx);
for (const n of ["planStack", "buildOfferStack", "judgeOffer"]) if (typeof engine[n] !== "function") throw new Error("missing " + n);
writeFileSync(OUT, out);
console.log(`StackEngine.js written (${names.length} exports, ${out.length} bytes)`);
